"""snippets/sw-brand-counts.liquid: JSON {vendor: product count} for the listing filters' brand order
(the prototype sorts brands by catalogue size). From prototype/products.json with the corrected
Azzaro / Boucheron vendors. Re-run when the catalogue changes a lot."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
P = {str(p["id"]): p for p in json.load(open(ROOT / "prototype/products.json"))}
for f in json.load(open(ROOT / "docs/seo/brand_mixup_fix_2026-10-26.json"))["products"]:
    P[f["id"].rsplit("/", 1)[1]]["brand"] = f["vendor"]
c = {}
for p in P.values():
    c[p["brand"]] = c.get(p["brand"], 0) + 1
c = dict(sorted(c.items(), key=lambda x: -x[1]))
(ROOT / "theme/snippets/sw-brand-counts.liquid").write_text(
    "{%- comment -%} GENERATED by tools/theme/build_brand_counts.py: products per brand (filter order) {%- endcomment -%}\n"
    + json.dumps(c, ensure_ascii=False))
print(len(c), "brands")
